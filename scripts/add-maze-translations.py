def main():
    for lang_code, new_trans in translations.items():
        locale_file = os.path.join(LOCALES_DIR, f'{lang_code}.json')

        # Read existing translations
        with open(locale_file, 'r', encoding='utf-8') as f:
            data = json.load(f)

        # Add new translations (skip if they already exist)
        added_count = 0
        for key, value in new_trans.items():
            if key not in data:
                data[key] = value
                added_count += 1

        # Write back
        with open(locale_file, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        print(f"✓ {lang_code}.json: Added {added_count} maze translations")

if __name__ == '__main__':
    main()
    print("\n✅ All maze translations added successfully!")
