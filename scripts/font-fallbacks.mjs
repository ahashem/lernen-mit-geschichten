#!/usr/bin/env node
/**
 * Writes src/styles/font-fallbacks.css: for each web font, a font the device already has, resized and re-spaced to
 * the web font's metrics. Until the web font arrives the text is set in this stand-in, so the swap changes the
 * letterforms but moves no line (ux/02 Typography). Same method as Astro's and fontaine's optimised fallbacks:
 * a size-adjust for width, then ascent, descent and line-gap overrides from the web font's own metrics.
 *
 * - Latin: the stand-in is Arial (Helvetica, Liberation Sans and Roboto are close), and the width comes from
 *   capsize's average character width.
 * - Arabic and Urdu: capsize measures widths on Latin letters only, and these scripts change shape with context, so
 *   the stand-in is the Noto face Android and iOS ship, and the width ratio was measured by rendering about 10,000
 *   characters of the stories' own titles and text in Chromium with both faces. Re-measure after changing a font.
 *
 * local() matches a font's full or PostScript name, so each stand-in lists both.
 *
 * Run after changing a font: node scripts/font-fallbacks.mjs
 */
import { writeFileSync } from 'node:fs';
import { fromFile } from '@capsizecss/unpack/fs';
import { format, resolveConfig } from 'prettier';

// Capsize's metrics for Arial (the same numbers Astro ships).
const ARIAL = { unitsPerEm: 2048, xWidthAvg: 913 };
const ARIAL_BOLD = { unitsPerEm: 2048, xWidthAvg: 983 };
const SANS = ['Arial', 'ArialMT', 'Helvetica', 'Liberation Sans', 'Roboto'];
const SANS_BOLD = ['Arial Bold', 'Arial-BoldMT', 'Helvetica Bold', 'Liberation Sans Bold', 'Roboto Bold'];

const FACES = [
  { family: 'Baloo 2', weight: 700, file: 'baloo-2/files/baloo-2-latin-700-normal.woff2', local: SANS_BOLD, latin: ARIAL_BOLD },
  { family: 'Andika', weight: 400, file: 'andika/files/andika-latin-400-normal.woff2', local: SANS, latin: ARIAL },
  { family: 'Andika', weight: 700, file: 'andika/files/andika-latin-700-normal.woff2', local: SANS_BOLD, latin: ARIAL_BOLD },
  {
    family: 'Baloo Bhaijaan 2',
    weight: 700,
    file: 'baloo-bhaijaan-2/files/baloo-bhaijaan-2-arabic-700-normal.woff2',
    local: ['Noto Naskh Arabic Bold', 'NotoNaskhArabic-Bold'],
    width: 1.0629,
  },
  {
    family: 'Noto Naskh Arabic',
    weight: 400,
    file: 'noto-naskh-arabic/files/noto-naskh-arabic-arabic-400-normal.woff2',
    local: ['Noto Naskh Arabic Regular', 'Noto Naskh Arabic', 'NotoNaskhArabic-Regular'],
    width: 1,
  },
  {
    family: 'Noto Naskh Arabic',
    weight: 700,
    file: 'noto-naskh-arabic/files/noto-naskh-arabic-arabic-700-normal.woff2',
    local: ['Noto Naskh Arabic Bold', 'NotoNaskhArabic-Bold'],
    width: 1,
  },
  {
    family: 'Gulzar',
    weight: 400,
    file: 'gulzar/files/gulzar-arabic-400-normal.woff2',
    local: ['Noto Nastaliq Urdu Regular', 'Noto Nastaliq Urdu', 'NotoNastaliqUrdu-Regular'],
    width: 0.8686,
  },
];

const pct = n => `${Number.parseFloat((n * 100).toFixed(4))}%`;

let css = `/* Generated by scripts/font-fallbacks.mjs: metric-matched stand-ins for the web fonts. Do not edit. */\n`;
for (const { family, weight, file, local, latin, width } of FACES) {
  const m = await fromFile(new URL(`../node_modules/@fontsource/${file}`, import.meta.url).pathname);
  const sizeAdjust = width ?? m.xWidthAvg / m.unitsPerEm / (latin.xWidthAvg / latin.unitsPerEm);
  const em = m.unitsPerEm * sizeAdjust;
  css += `
@font-face {
  font-family: '${family} Fallback';
  font-weight: ${weight};
  src: ${local.map(n => `local('${n}')`).join(', ')};
  size-adjust: ${pct(sizeAdjust)};
  ascent-override: ${pct(m.ascent / em)};
  descent-override: ${pct(Math.abs(m.descent) / em)};
  line-gap-override: ${pct(m.lineGap / em)};
}
`;
}
const out = new URL('../src/styles/font-fallbacks.css', import.meta.url);
writeFileSync(out, await format(css, { ...(await resolveConfig(out.pathname)), filepath: out.pathname }));
console.log('wrote src/styles/font-fallbacks.css');
